"""Write docs/PARAMETER_EDITORS.md: for every module, how each parameter is edited (generated from param_schema)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import apex_vision.tools  # noqa: E402,F401
from apex_vision.core import param_schema as ps  # noqa: E402
from apex_vision.core.registry import create_tool_instance, list_all_tools  # noqa: E402

LABEL = {"bool": "switch", "enum": "drop-down", "combo": "drop-down + typed", "int": "whole number", "float": "number", "text": "text box",
         "path": "file + Browse", "dir": "folder + Browse", "rect": "X Y W H fields", "point": "X Y fields", "line": "X1 Y1 X2 Y2 fields",
         "points": "list, one x, y per line", "rgb": "R G B fields + swatch", "code": "script editor", "device": "drop-down of cameras",
         "flow": "drop-down of flows"}


def main():
    lines = ["# Module parameter editors", "",
             "Generated by `python scripts/gen_param_editors_doc.py` from `apex_vision/core/param_schema.py`. Every parameter is",
             "edited with the control that fits it; free text is used only where no fixed set of values exists.", ""]
    totals = {}
    for name in sorted(list_all_tools()):
        tool = create_tool_instance(name, "t")
        lines += [f"## {name}", "", "| Parameter | Editor | Choices / limits |", "|---|---|---|"]
        for key, default in tool.parameters.items():
            s = ps.spec_for(name, key, default)
            totals[s["kind"]] = totals.get(s["kind"], 0) + 1
            extra = " / ".join(s["choices"]) if "choices" in s else (f"{s['min']:g} to {s['max']:g}" + (f" {s['unit']}" if s.get("unit") else "")
                                                                   if s.get("min", -1e12) > -1e11 else s.get("hint", ""))
            lines.append(f"| {s['label']} | {LABEL.get(s['kind'], s['kind'])} | {extra} |")
        lines.append("")
    lines += ["## Totals", "", ", ".join(f"{LABEL.get(k, k)}: {v}" for k, v in sorted(totals.items())), ""]
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "PARAMETER_EDITORS.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", path, totals)


if __name__ == "__main__":
    main()
